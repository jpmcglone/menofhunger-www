/** Canonical source: design/*.json. Regenerate both clients and the importable SVG assets. */
import fs from 'node:fs'
import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ios = path.resolve(root, '../menofhunger-ios/MenOfHunger')
const read = name => JSON.parse(fs.readFileSync(path.join(root, name), 'utf8'))
const catalog = read('design/icon-catalog.json')
const stroked = Object.fromEntries(['catchup', 'gif', 'share'].map(name => [name, read(`design/${name}-icon.json`)]))
const badges = read('design/badge-vectors.json')
const marv = read('design/marv-mark.json')
const tabler = read('node_modules/@iconify-json/tabler/icons.json').icons
const symbols = []
const bodies = {}
for (const [name, def] of Object.entries(catalog)) {
  for (const selected of [false, true]) {
    const state = selected ? 'selected' : 'default'
    let body
    if (def.figma) {
      // Exact Figma export geometry; template paint follows the semantic consumer tint.
      const svg = fs.readFileSync(path.join(root, `design/figma-icons/${name}-${state}.svg`), 'utf8')
      const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
      body = `<g fill="none">${inner.replaceAll('#F4F4F5', 'currentColor')}</g>`
    }
    else if (badges[name]) body = badges[name]
    else if (stroked[name]) {
      const shape = stroked[name]
      body = `<g fill="none" stroke="currentColor" stroke-width="${selected ? shape.selectedStrokeWidth : shape.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${shape.paths.map(d => `<path d="${d}"/>`).join('')}</g>`
    }
    else if (name === 'marv') body = marv.shapes[selected ? 'loading' : 'standard'].map(p => `<path d="${p.d}" fill="${p.role === 'orange' ? '#ff8500' : 'currentColor'}"/>`).join('')
    else {
      const glyph = tabler[selected ? def.webSelected : def.web]
      if (!glyph) throw Error(`Unknown glyph: ${name}`)
      body = glyph.body
      if (selected && name === 'search') body = '<circle cx="10" cy="10" r="7" fill="currentColor" fill-opacity="0.5"/>' + body
      if (selected && def.selectedTreatment === 'bold') body = body.replaceAll('stroke-width="2"', 'stroke-width="2.6"')
    }
    bodies[`${name}/${state}`] = body
    symbols.push(`<symbol id="${name}-${state}" viewBox="0 0 24 24">${body}</symbol>`)
  }
}
fs.mkdirSync(path.join(root, 'public/icons'), { recursive: true })
fs.writeFileSync(path.join(root, 'public/icons/moh.svg'), `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join('\n')}</svg>\n`)
fs.writeFileSync(path.join(root, 'design/icon-vectors.json'), JSON.stringify(bodies, null, 2) + '\n')
function asset(name, bodyForTheme) {
  const dir = path.join(ios, 'Assets.xcassets', `${name}.imageset`)
  fs.mkdirSync(dir, { recursive: true })
  const images = ['light', 'dark'].map(theme => {
    fs.writeFileSync(path.join(dir, `${theme}.svg`), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24">${bodyForTheme(theme)}</svg>\n`)
    return { filename: `${theme}.svg`, idiom: 'universal', ...(theme === 'dark' ? { appearances: [{ appearance: 'luminosity', value: 'dark' }] } : {}) }
  })
  fs.writeFileSync(path.join(dir, 'Contents.json'), JSON.stringify({ images, info: { author: 'xcode', version: 1 }, properties: { 'preserves-vector-representation': true } }, null, 2) + '\n')
}
for (const [key, body] of Object.entries(bodies)) {
  if (key.startsWith('marv/')) continue
  const name = 'MOHIcon-' + key.replace('/', '-')
  const dir = path.join(ios, 'Assets.xcassets', name + '.imageset')
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(path.join(dir, 'icon.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24">${body.replaceAll('currentColor', '#000000')}</svg>\n`)
  fs.writeFileSync(path.join(dir, 'Contents.json'), JSON.stringify({ images: [{ filename: 'icon.svg', idiom: 'universal' }], info: { author: 'xcode', version: 1 }, properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' } }, null, 2) + '\n')
}
for (const [state, paths] of Object.entries(marv.shapes)) asset(state === 'standard' ? 'MARVMark' : 'MARVLoader', theme => paths.map(p => `<path d="${p.d}" fill="${marv.colors[theme][p.role]}"/>`).join(''))
const swift = `// Generated by menofhunger-www/scripts/build-icon-library.mjs. Edit design/icon-catalog.json.\nnonisolated enum MOHIconName: String, CaseIterable {\n  case ${Object.keys(catalog).map(k => '`' + k + '`').join(', ')}\n}\n`
fs.writeFileSync(path.join(ios, 'App/DesignSystem/Components/MOHIconName.swift'), swift)
execFileSync('xcrun', ['swift-format', 'format', '--in-place', '--configuration', path.resolve(ios, '../.swift-format'), path.join(ios, 'App/DesignSystem/Components/MOHIconName.swift')])
console.log(`Generated ${Object.keys(catalog).length} semantic icons with default/selected states and MARV vector assets.`)
